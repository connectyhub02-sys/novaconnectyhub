export function listTuringStressScenarios(input: {
  panel?: TuringPanelScope;
  surface?: TuringScenarioSurface;
  category?: TuringScenarioCategory;
  minSeverity?: TuringScenarioSeverity;
} = {}) {
  return turingStressScenarios.filter((scenario) => {
    if (input.panel && !scenario.panels.includes(input.panel) && !scenario.panels.includes("shared")) {
      return false;
    }

    if (input.surface && !scenario.surfaces.includes(input.surface)) {
      return false;
    }

    if (input.category && scenario.category !== input.category) {
      return false;
    }

    if (input.minSeverity && severityRank(scenario.severity) < severityRank(input.minSeverity)) {
      return false;
    }

    return true;
  });
}

export function getTuringStressCoverageSummary() {
  return {
    total: turingStressScenarios.length,
    categories: uniqueSorted(turingStressScenarios.map((scenario) => scenario.category)),
    panels: uniqueSorted(turingStressScenarios.flatMap((scenario) => scenario.panels)),
    surfaces: uniqueSorted(turingStressScenarios.flatMap((scenario) => scenario.surfaces)),
    highOrCritical: turingStressScenarios.filter((scenario) => severityRank(scenario.severity) >= severityRank("high")).length,
  };
}

export function buildTuringScenarioRunbookMarkdown(scenarios: TuringStressScenario[] = turingStressScenarios) {
  return scenarios
    .map((scenario) => [
      `### ${scenario.id}: ${scenario.title}`,
      `- Categoria: ${scenario.category}`,
      `- Severidade: ${scenario.severity}`,
      `- Paineis: ${scenario.panels.join(", ")}`,
      `- Superficies: ${scenario.surfaces.join(", ")}`,
      `- Acao esperada: ${scenario.expectedAction}`,
      scenario.setupContext ? `- Contexto: ${scenario.setupContext}` : null,
      `- Mensagens de teste: ${scenario.leadMessages.join(" | ")}`,
      `- Como deve lidar: ${scenario.expectedHandling}`,
      `- Sinais de quebra: ${scenario.failureSignals.join("; ")}`,
      `- Criterios de aprovacao: ${scenario.passCriteria.join("; ")}`,
    ].filter(Boolean).join("\n"))
    .join("\n\n");
}

function severityRank(severity: TuringScenarioSeverity) {
  if (severity === "critical") return 4;
  if (severity === "high") return 3;
  if (severity === "medium") return 2;
  return 1;
}

function uniqueSorted<T extends string>(values: T[]) {
  return Array.from(new Set(values)).sort((left, right) => left.localeCompare(right));
}
